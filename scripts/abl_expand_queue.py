"""Expansion-round queue for the component-ablation tuning (the research plan
S6, katchers only): each tuned variant (sasrec_txnpos_final2, txf_txn_causal_itempos_final2,
bert4rec_txnpos) gets every unseen 1-step neighbour of its current best -- the mean over
val seeds 0-4 of the MASKED NDCG@10 -- on each axis. Ladders and job args are the katchers
entry of scripts/bl_expand_queue.py: dim 32..1024 (x2), dropout {0, 0.1, 0.3, 0.5, 0.7},
lr 6.25e-5..8e-3 (x2); every job gets --epochs 500.
bert4rec_txnpos's mask_prob is held at --mask-prob (other values are not read). --models
leaves out a variant that has met its stop rule. The comment lines give, for each unseen
neighbour of a best config, the gain of the last step taken in that direction (the stop
rule's boundary check).

    uv run python scripts/abl_expand_queue.py --mask-prob 0.4 > configs/queue/abl_k_r1.txt
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

from mvcp.compare import parse_seeds

MODELS = ("sasrec_txnpos_final2", "txf_txn_causal_itempos_final2", "bert4rec_txnpos")
AXES = [[32, 64, 128, 256, 512, 1024], [0.0, 0.1, 0.3, 0.5, 0.7],
        [0.0000625, 0.000125, 0.00025, 0.0005, 0.001, 0.002, 0.004, 0.008]]
PAT = re.compile(rf"^({'|'.join(MODELS)})_lr([^_]+)_d(\d+)_do([^_]+)(?:_mp([^_]+))?"
                 r"_val_seed(\d+)\.json$")

ap = argparse.ArgumentParser()
ap.add_argument("--dir", default="results/katchers")
ap.add_argument("--seeds", default="0-4")
ap.add_argument("--models", default=",".join(MODELS))
ap.add_argument("--mask-prob", type=float, default=None,
                help="bert4rec_txnpos's fixed mask_prob")
a = ap.parse_args()
seeds = parse_seeds(a.seeds)
models = a.models.split(",")
if "bert4rec_txnpos" in models and a.mask_prob is None:
    ap.error("bert4rec_txnpos needs --mask-prob")

seen = defaultdict(lambda: defaultdict(list))        # model -> (dim, do, lr) -> [scores]
for f in Path(a.dir).glob("*_val_seed*.json"):
    m = PAT.match(f.name)
    if not m or m[1] not in models or int(m[6]) not in seeds:
        continue
    if (float(m[5]) if m[5] else None) != (a.mask_prob if m[1] == "bert4rec_txnpos" else None):
        continue
    seen[m[1]][(int(m[3]), float(m[4]), float(m[2]))].append(
        json.loads(f.read_text())["full_catalog"]["overall"]["ndcg@10"])
mean = {m: {c: float(np.mean(v)) for c, v in cells.items() if len(v) == len(seeds)}
        for m, cells in seen.items()}


def step(cfg, i, k):
    """cfg moved k steps along axis i (None off the ladder)."""
    j = AXES[i].index(cfg[i]) + k
    return cfg[:i] + (AXES[i][j],) + cfg[i + 1:] if 0 <= j < len(AXES[i]) else None


fmt = lambda c: f"dim {c[0]} / dropout {c[1]:g} / lr {c[2]:g}"   # noqa: E731
todo, notes = {}, []
for m in models:
    c = max(mean[m], key=mean[m].get)
    notes.append(f"# {m} current best {fmt(c)} = {mean[m][c]:.5f} ({len(mean[m])} seen)")
    todo[m] = []
    for i in range(3):
        for k in (-1, 1):
            x, back = step(c, i, k), step(c, i, -k)
            if not x or x in mean[m]:
                continue
            todo[m].append(x)
            if back in mean[m]:
                notes.append(f"#   boundary → {fmt(x)}: gain of the last step in that direction "
                             f"{(mean[m][c] - mean[m][back]) / mean[m][c]:+.2%} "
                             f"({mean[m][c] - mean[m][back]:+.5f})")

print(f"# Position variants, tuning expansion round (Katcher's, val, seed {a.seeds}) — "
      "unseen one-step neighbours of the current best; generated by scripts/abl_expand_queue.py")
print("\n".join(notes))
for s in seeds:
    for m in models:
        mp = f" --mask-prob {a.mask_prob:g}" if m == "bert4rec_txnpos" else ""
        for d, p, lr in todo[m]:
            print(f"{m} {s} --dim {d} --dropout {p:g} --lr {lr:g}{mp} --epochs 500 "
                  "--eval-split val")
