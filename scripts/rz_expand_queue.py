"""Expansion-round queue for the REES46 tuning (S6 -- the PD
study's round-2 rule): each model gets every unseen 1-step neighbour of its current best
(5-seed mean of val MASKED NDCG@10, the selection metric) on each axis.

  * axis ladders: dim 32..1024 (x2), dropout {0, 0.1, 0.3, 0.5, 0.7}, lr 6.25e-5..8e-3 (x2);
  * SASRec only: neighbours of EVERY config within 0.5% of its best;
  * SASRec only: every config TxnCausal sees that SASRec has not (superset rule).
The comment lines also give, for each unseen neighbour of a best config, the gain of the
last step taken in that direction (the stop rule's boundary check).

    uv run python scripts/rz_expand_queue.py > configs/queue/rz_p1_r1.txt
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

from mvcp.compare import parse_seeds

AXES = [[32, 64, 128, 256, 512, 1024], [0.0, 0.1, 0.3, 0.5, 0.7],
        [0.0000625, 0.000125, 0.00025, 0.0005, 0.001, 0.002, 0.004, 0.008]]
TIE = 0.005                                   # SASRec: configs within 0.5% of its best
PAT = re.compile(r"^(sasrec|txf_txn_causal)_lr([^_]+)_d(\d+)_do([^_]+)_val_seed(\d+)\.json$")

ap = argparse.ArgumentParser()
ap.add_argument("--dir", default="results/rees46")
ap.add_argument("--seeds", default="0-4")
a = ap.parse_args()
seeds = parse_seeds(a.seeds)

seen = defaultdict(lambda: defaultdict(list))        # model -> (dim, do, lr) -> [scores]
for f in Path(a.dir).glob("*_val_seed*.json"):
    m = PAT.match(f.name)
    if m and int(m[5]) in seeds:
        seen[m[1]][(int(m[3]), float(m[4]), float(m[2]))].append(
            json.loads(f.read_text())["full_catalog"]["overall"]["ndcg@10"])
mean = {m: {c: float(np.mean(v)) for c, v in cells.items() if len(v) == len(seeds)}
        for m, cells in seen.items()}


def step(cfg, i, k):
    """cfg moved k steps along axis i (None off the ladder)."""
    j = AXES[i].index(cfg[i]) + k
    return cfg[:i] + (AXES[i][j],) + cfg[i + 1:] if 0 <= j < len(AXES[i]) else None


def neighbours(cfg):
    return [x for i in range(3) for k in (-1, 1) if (x := step(cfg, i, k))]


fmt = lambda c: f"dim {c[0]} / dropout {c[1]:g} / lr {c[2]:g}"   # noqa: E731
todo, notes = defaultdict(list), []
for m in ("sasrec", "txf_txn_causal"):
    top = max(mean[m].values())
    for c in sorted((c for c, v in mean[m].items()
                     if top - v <= (TIE * top if m == "sasrec" else 0.0)),
                    key=lambda c: -mean[m][c]):
        notes.append(f"# {m} current best {fmt(c)} = {mean[m][c]:.5f} ({len(mean[m])} seen)")
        todo[m] += [x for x in neighbours(c) if x not in mean[m] and x not in todo[m]]
        for i in range(3):
            for k in (-1, 1):
                x, back = step(c, i, k), step(c, i, -k)
                if x and x not in mean[m] and back in mean[m]:
                    notes.append(f"#   boundary → {fmt(x)}: gain of the last step in that direction "
                                 f"{(mean[m][c] - mean[m][back]) / mean[m][c]:+.2%}")
probes = [c for c in set(mean["txf_txn_causal"]) | set(todo["txf_txn_causal"])
          if c not in mean["sasrec"] and c not in todo["sasrec"]]
probes.sort()
notes.append(f"# conservative probes for SASRec (settings seen only by TxnCausal): {probes}")
todo["sasrec"] += probes

print(f"# REES46 tuning, expansion round (main data, val, seed {a.seeds}) — one-step neighbours of the current best + SASRec probes; generated by scripts/rz_expand_queue.py")
print("\n".join(notes))
for s in seeds:
    for m in ("sasrec", "txf_txn_causal"):
        for d, p, lr in todo[m]:
            print(f"{m} {s} --data rees46 --dim {d} --dropout {p:g} --lr {lr:g} --eval-split val")
