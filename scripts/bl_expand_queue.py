"""Expansion-round queue for the baseline tuning (S6/S7):
each baseline (gru4rec, bert4rec) gets every unseen 1-step neighbour of its current best --
the mean over the tuning seeds of the dataset's selection metric -- on each axis.

  katchers       val MASKED NDCG@10, seeds 0-4; ladders dim 32..1024 (x2),
                 dropout {0, 0.1, 0.3, 0.5, 0.7}, lr 6.25e-5..8e-3 (x2); every job gets
                 --epochs 500 (the data yaml's cap of 100 belongs to the earlier runs)
  instacart_all  val UNMASKED NDCG@10, seeds 0-2; ladders dim 64..1024 (x2),
                 dropout {0, 0.1, 0.3, 0.5}, lr 2.5e-4..8e-3 (x2)
BERT4Rec's mask_prob is held at --mask-prob (fixed before the grid; other values are not
read). --models leaves out a baseline that has met its stop rule. --max-dim caps the dim
ladder: wider configs are neither read nor proposed. The comment lines give,
for each unseen neighbour of a best config, the gain of the last step taken in that
direction (the stop rule's boundary check).

    uv run python scripts/bl_expand_queue.py --data katchers --mask-prob 0.4 \
        > configs/queue/bl_k_r1.txt
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

from mvcp.compare import parse_seeds

DATA = {  # selection protocol, tuning seeds, axis ladders (dim, dropout, lr), job args
    "katchers": ("full_catalog", "0-4",
                 [[32, 64, 128, 256, 512, 1024], [0.0, 0.1, 0.3, 0.5, 0.7],
                  [0.0000625, 0.000125, 0.00025, 0.0005, 0.001, 0.002, 0.004, 0.008]],
                 "", " --epochs 500"),
    "instacart_all": ("full_nomask", "0-2",
                      [[64, 128, 256, 512, 1024], [0.0, 0.1, 0.3, 0.5],
                       [0.00025, 0.0005, 0.001, 0.002, 0.004, 0.008]],
                      " --data instacart_all", ""),
}
PAT = re.compile(r"^(gru4rec|bert4rec)_lr([^_]+)_d(\d+)_do([^_]+)(?:_mp([^_]+))?"
                 r"_val_seed(\d+)\.json$")

ap = argparse.ArgumentParser()
ap.add_argument("--data", choices=tuple(DATA), required=True)
ap.add_argument("--dir", default=None, help="default results/<data>")
ap.add_argument("--seeds", default=None, help="default: the dataset's tuning seeds")
ap.add_argument("--models", default="gru4rec,bert4rec")
ap.add_argument("--mask-prob", type=float, default=None, help="bert4rec's fixed mask_prob")
ap.add_argument("--max-dim", type=int, default=None, help="cap of the dim ladder")
a = ap.parse_args()
protocol, seeds_default, AXES, data_arg, tail = DATA[a.data]
if a.max_dim:
    AXES = [[d for d in AXES[0] if d <= a.max_dim]] + AXES[1:]
seeds = parse_seeds(a.seeds or seeds_default)
models = a.models.split(",")
if "bert4rec" in models and a.mask_prob is None:
    ap.error("bert4rec needs --mask-prob")

seen = defaultdict(lambda: defaultdict(list))        # model -> (dim, do, lr) -> [scores]
for f in Path(a.dir or f"results/{a.data}").glob("*_val_seed*.json"):
    m = PAT.match(f.name)
    if not m or m[1] not in models or int(m[6]) not in seeds or int(m[3]) not in AXES[0]:
        continue
    if (float(m[5]) if m[5] else None) != (a.mask_prob if m[1] == "bert4rec" else None):
        continue
    seen[m[1]][(int(m[3]), float(m[4]), float(m[2]))].append(
        json.loads(f.read_text())[protocol]["overall"]["ndcg@10"])
mean = {m: {c: float(np.mean(v)) for c, v in cells.items() if len(v) == len(seeds)}
        for m, cells in seen.items()}


def step(cfg, i, k):
    """cfg moved k steps along axis i (None off the ladder)."""
    j = AXES[i].index(cfg[i]) + k
    return cfg[:i] + (AXES[i][j],) + cfg[i + 1:] if 0 <= j < len(AXES[i]) else None


fmt = lambda c: f"dim {c[0]} / dropout {c[1]:g} / lr {c[2]:g}"   # noqa: E731
todo, notes = {}, []
for m in models:
    c = max(mean[m], key=mean[m].get)
    notes.append(f"# {m} current best {fmt(c)} = {mean[m][c]:.5f} ({len(mean[m])} seen)")
    todo[m] = []
    for i in range(3):
        for k in (-1, 1):
            x, back = step(c, i, k), step(c, i, -k)
            if not x or x in mean[m]:
                continue
            todo[m].append(x)
            if back in mean[m]:
                notes.append(f"#   boundary → {fmt(x)}: gain of the last step in that direction "
                             f"{(mean[m][c] - mean[m][back]) / mean[m][c]:+.2%} "
                             f"({mean[m][c] - mean[m][back]:+.5f})")

print(f"# Baseline tuning, expansion round ({a.data}, val, seed {a.seeds or seeds_default}) — "
      "unseen one-step neighbours of the current best; generated by scripts/bl_expand_queue.py")
print("\n".join(notes))
for s in seeds:
    for m in models:
        mp = f" --mask-prob {a.mask_prob:g}" if m == "bert4rec" else ""
        for d, p, lr in todo[m]:
            print(f"{m} {s}{data_arg} --dim {d} --dropout {p:g} --lr {lr:g}{mp}{tail} "
                  "--eval-split val")
