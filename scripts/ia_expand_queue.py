"""Expansion-round queue for the ALL tuning (S6, 1-B --
the PD study's round-2 rule): each model gets every unseen 1-step neighbour of its current
best (3-seed mean of val unmasked NDCG@10) on each axis.

  * axis ladders: dim 64..1024 (x2), dropout {0, 0.1, 0.3, 0.5}, lr 2.5e-4..8e-3 (x2);
  * SASRec only: neighbours of EVERY config within 0.0005 of its best;
  * SASRec only: every config TxnCausal sees that SASRec has not (superset rule).

    uv run python scripts/ia_expand_queue.py > configs/queue/ia_p1_r1.txt
"""
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

OUT = Path("results/instacart_all")
SEEDS = range(3)
AXES = [[64, 128, 256, 512, 1024], [0.0, 0.1, 0.3, 0.5],
        [0.00025, 0.0005, 0.001, 0.002, 0.004, 0.008]]
PAT = re.compile(r"^(sasrec|txf_txn_causal)_lr([^_]+)_d(\d+)_do([^_]+)_val_seed(\d+)\.json$")

seen = defaultdict(lambda: defaultdict(list))        # model -> (dim, do, lr) -> [scores]
for f in OUT.glob("*_val_seed*.json"):
    m = PAT.match(f.name)
    if m and int(m[5]) in SEEDS:
        seen[m[1]][(int(m[3]), float(m[4]), float(m[2]))].append(
            json.loads(f.read_text())["full_nomask"]["overall"]["ndcg@10"])
mean = {m: {c: float(np.mean(v)) for c, v in cells.items() if len(v) == len(SEEDS)}
        for m, cells in seen.items()}


def neighbours(cfg):
    out = []
    for i, ladder in enumerate(AXES):
        j = ladder.index(cfg[i])
        for k in (j - 1, j + 1):
            if 0 <= k < len(ladder):
                out.append(cfg[:i] + (ladder[k],) + cfg[i + 1:])
    return out


todo, notes = defaultdict(list), []
for m in ("sasrec", "txf_txn_causal"):
    top = max(mean[m].values())
    for c in sorted((c for c, v in mean[m].items()
                     if top - v < (0.0005 if m == "sasrec" else 1e-12)),
                    key=lambda c: -mean[m][c]):
        notes.append(f"# {m} current best dim {c[0]} / dropout {c[1]:g} / lr {c[2]:g} = {mean[m][c]:.5f}")
        todo[m] += [x for x in neighbours(c) if x not in mean[m] and x not in todo[m]]
probes = [c for c in set(mean["txf_txn_causal"]) | set(todo["txf_txn_causal"])
          if c not in mean["sasrec"] and c not in todo["sasrec"]]
probes.sort()
notes.append(f"# conservative probes for SASRec (settings seen only by TxnCausal): {probes}")
todo["sasrec"] += probes

print("# Instacart tuning, expansion round (val, seed 0-2) — one-step neighbours of the current best + SASRec probes; generated by scripts/ia_expand_queue.py")
print("\n".join(notes))
for s in SEEDS:
    for m in ("sasrec", "txf_txn_causal"):
        for d, p, lr in todo[m]:
            print(f"{m} {s} --data instacart_all --dim {d} --dropout {p:g} --lr {lr:g} --eval-split val")
